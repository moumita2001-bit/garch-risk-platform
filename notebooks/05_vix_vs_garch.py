"""Week 5: how does my GARCH volatility compare with VIX?

VIX is the options market's forecast of S&P 500 volatility over the next
30 calendar days (about 21 trading days), in annualized percent. This script:
  1. lines up VIX with my GJR-GARCH-t forecast for the next day, both annualized;
  2. measures how closely they move together;
  3. compares both with the volatility that actually followed (next 21 days),
     which shows the variance risk premium: VIX tends to sit above it.
Writes docs/vix_vs_garch.md and docs/figures/06_vix_vs_garch.png.

Usage:
    python notebooks/05_vix_vs_garch.py
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from volrisk.models import GJRStudentTGARCH

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SPY_FILE = PROJECT_ROOT / "data" / "processed" / "spy.csv"
VIX_FILE = PROJECT_ROOT / "data" / "raw" / "vixcls.csv"
FIG_FILE = PROJECT_ROOT / "docs" / "figures" / "06_vix_vs_garch.png"
REPORT_FILE = PROJECT_ROOT / "docs" / "vix_vs_garch.md"
TRADING_DAYS = 252
HORIZON = 21  # VIX looks 30 calendar days ahead, about 21 trading days


def load() -> pd.DataFrame:
    spy = pd.read_csv(SPY_FILE, parse_dates=["date"]).set_index("date")
    r = (100 * spy["log_return"]).dropna()

    model = GJRStudentTGARCH(zero_mean=True)
    params = model.fit(r.to_numpy()).params
    sigma2 = model.conditional_variance(params, r.to_numpy())
    # sigma2[t] is the forecast for day t made with data up to t-1. Shift it so
    # each row holds the forecast made at the close of that day, like VIX.
    garch = pd.Series(np.sqrt(sigma2 * TRADING_DAYS), index=r.index).shift(-1)

    # Volatility that actually happened over the next 21 trading days
    future_sq = (r**2).rolling(HORIZON).mean().shift(-HORIZON)
    realized = np.sqrt(future_sq * TRADING_DAYS)

    vix = pd.read_csv(VIX_FILE, parse_dates=["date"]).set_index("date")["vixcls"]
    df = pd.DataFrame({"garch": garch, "realized": realized}).join(vix.rename("vix"), how="inner")
    return df.dropna(subset=["garch", "vix"]), params


def plot(df: pd.DataFrame) -> None:
    fig, ax = plt.subplots(figsize=(11, 4))
    ax.plot(df.index, df["vix"], lw=0.8, color="#993C1D", label="VIX (options market)")
    ax.plot(df.index, df["garch"], lw=0.8, color="#185FA5", label="GJR-GARCH-t forecast")
    ax.set_ylabel("Annualized volatility (%)")
    ax.set_title("Market-implied vs model volatility for SPY")
    ax.legend(frameon=False)
    fig.tight_layout()
    FIG_FILE.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG_FILE)
    plt.close(fig)


def main() -> None:
    df, params = load()
    plot(df)

    both = df.dropna()  # rows where the next 21 days are known
    corr_level = df["garch"].corr(df["vix"])
    corr_change = df["garch"].diff().corr(df["vix"].diff())
    vrp = both["vix"] - both["realized"]
    err_vix = (both["vix"] - both["realized"]).abs().mean()
    err_garch = (both["garch"] - both["realized"]).abs().mean()

    text = f"""# Week 5: GJR-GARCH-t volatility vs VIX

{len(df):,} days from {df.index[0].date()} to {df.index[-1].date()}.
Model fitted once on the full sample (gamma = {params.gamma:.3f}, nu = {params.nu:.2f}).
Generated by `notebooks/05_vix_vs_garch.py`.

![VIX vs GARCH](figures/06_vix_vs_garch.png)

| Measure | Value |
| --- | --- |
| Correlation of levels | {corr_level:.3f} |
| Correlation of daily changes | {corr_change:.3f} |
| Average VIX | {df['vix'].mean():.1f}% |
| Average GARCH forecast | {df['garch'].mean():.1f}% |
| Average realized vol, next 21 days | {both['realized'].mean():.1f}% |
| Variance risk premium (VIX minus realized), average | {vrp.mean():+.1f} points |
| Share of days VIX was above realized | {100 * (vrp > 0).mean():.0f}% |
| Mean absolute error vs realized: VIX | {err_vix:.1f} points |
| Mean absolute error vs realized: GARCH | {err_garch:.1f} points |

- VIX and the model share the same crises, so the level correlation is high.
- VIX usually sits above the volatility that follows: investors pay extra
  for protection against crashes (the variance risk premium).
- Note: this comparison uses a full-sample fit, so it is descriptive,
  not an out-of-sample forecast test.
"""
    REPORT_FILE.write_text(text)
    print(f"Correlation (levels) {corr_level:.3f}, (changes) {corr_change:.3f}")
    print(f"Avg VIX {df['vix'].mean():.1f}%, GARCH {df['garch'].mean():.1f}%, "
          f"realized {both['realized'].mean():.1f}%, VRP {vrp.mean():+.1f}, "
          f"VIX above realized {100 * (vrp > 0).mean():.0f}% of days")
    print(f"MAE vs realized: VIX {err_vix:.1f}, GARCH {err_garch:.1f}")
    print(f"Saved {REPORT_FILE.relative_to(PROJECT_ROOT)} and {FIG_FILE.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
