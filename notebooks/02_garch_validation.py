"""Week 2 validation: does my GARCH(1,1) match the `arch` package on real SPY data?

Fits both implementations to the same returns (in percent), compares the
estimates, and writes the results to docs/garch_validation.md.

Usage:
    python notebooks/02_garch_validation.py
"""

from pathlib import Path

import numpy as np
import pandas as pd
from arch import arch_model

from volrisk.models import GARCH, GarchParams

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_FILE = PROJECT_ROOT / "data" / "processed" / "spy.csv"
REPORT_FILE = PROJECT_ROOT / "docs" / "garch_validation.md"
TRADING_DAYS = 252


def load_returns() -> pd.Series:
    df = pd.read_csv(DATA_FILE, parse_dates=["date"]).set_index("date")
    return (100 * df["log_return"]).dropna()


def fit_arch_package(r: pd.Series):
    model = arch_model(r, mean="Constant", vol="GARCH", p=1, q=1, dist="normal")
    res = model.fit(disp="off")
    p = res.params
    params = GarchParams(
        mu=float(p["mu"]), omega=float(p["omega"]),
        alpha=float(p["alpha[1]"]), beta=float(p["beta[1]"]),
    )
    return params, float(res.loglikelihood)


def annual_vol(params: GarchParams) -> float:
    return float(np.sqrt(params.long_run_variance * TRADING_DAYS))


def main() -> None:
    r = load_returns()
    model = GARCH()

    mine = model.fit(r.to_numpy())
    theirs, theirs_ll = fit_arch_package(r)

    # Score arch's parameters with MY likelihood: if both estimators found the
    # same optimum, the two numbers below should be almost identical.
    theirs_ll_on_mine = model.log_likelihood(theirs, r.to_numpy())

    rows = [
        ("mu", mine.params.mu, theirs.mu),
        ("omega", mine.params.omega, theirs.omega),
        ("alpha", mine.params.alpha, theirs.alpha),
        ("beta", mine.params.beta, theirs.beta),
        ("alpha + beta", mine.params.persistence, theirs.persistence),
        ("half-life (days)", mine.params.half_life, theirs.half_life),
        ("long-run vol, annualized (%)", annual_vol(mine.params), annual_vol(theirs)),
    ]
    table = "\n".join(
        f"| {name} | {a:.4f} | {b:.4f} | {a - b:+.4f} |" for name, a, b in rows
    )

    sample_vol = float(r.std() * np.sqrt(TRADING_DAYS))
    text = f"""# Week 2 validation: my GARCH(1,1) vs the `arch` package

Data: {len(r):,} daily SPY log returns in percent, {r.index[0].date()} to {r.index[-1].date()}.
Generated by `notebooks/02_garch_validation.py`.

| Quantity | Mine | arch | Difference |
| --- | --- | --- | --- |
{table}

## Log-likelihood

| | Value |
| --- | --- |
| My fit, scored by my likelihood | {mine.log_likelihood:.2f} |
| arch's parameters, scored by my likelihood | {theirs_ll_on_mine:.2f} |
| arch's fit, scored by arch | {theirs_ll:.2f} |

Converged: {mine.converged} ({mine.message})

## Reading

- Sample annualized volatility is {sample_vol:.1f}%; the model's long-run level is
  {annual_vol(mine.params):.1f}%.
- Persistence of {mine.params.persistence:.3f} means a volatility shock loses half its
  effect in about {mine.params.half_life:.0f} trading days.
- Small differences come from how each package starts the variance recursion
  (I use the sample variance; arch uses an exponentially weighted backcast).
"""
    REPORT_FILE.write_text(text)

    print(f"{'':<30}{'mine':>10}{'arch':>10}")
    for name, a, b in rows:
        print(f"{name:<30}{a:>10.4f}{b:>10.4f}")
    print(f"\nLog-likelihood: mine {mine.log_likelihood:.2f}, arch {theirs_ll:.2f}")
    print(f"Saved report to {REPORT_FILE.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()