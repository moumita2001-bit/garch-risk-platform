"""Week 4: out-of-sample backtest of 99% VaR on SPY, normal vs Student-t GARCH.

For every day after the first 1,000, VaR is forecast using only earlier data
(re-fit every 21 days on a rolling 1,000-day window). The script counts
breaches, runs the Kupiec and Christoffersen tests, checks Basel zones,
saves a chart and writes docs/var_backtest.md.

Usage:
    python notebooks/04_var_backtest.py
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from volrisk.models import GARCH, StudentTGARCH
from volrisk.risk import basel_zone, christoffersen_test, kupiec_test, rolling_var

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_FILE = PROJECT_ROOT / "data" / "processed" / "spy.csv"
FIG_FILE = PROJECT_ROOT / "docs" / "figures" / "05_var_backtest.png"
REPORT_FILE = PROJECT_ROOT / "docs" / "var_backtest.md"

P = 0.01          # 99% VaR
WINDOW = 1000     # training days per fit
REFIT_EVERY = 21  # re-fit roughly monthly
BASEL_DAYS = 250


def load_returns() -> pd.Series:
    df = pd.read_csv(DATA_FILE, parse_dates=["date"]).set_index("date")
    return (100 * df["log_return"]).dropna()


def summarize(name: str, bt: pd.DataFrame) -> dict:
    b = bt["breach"].to_numpy()
    rolling_count = bt["breach"].rolling(BASEL_DAYS).sum().dropna()
    zones = rolling_count.astype(int).map(basel_zone)
    kup, chr_ = kupiec_test(b, P), christoffersen_test(b)
    return {
        "model": name,
        "days": len(b),
        "breaches": int(b.sum()),
        "expected": len(b) * P,
        "rate_pct": 100 * b.mean(),
        "kupiec_p": kup.p_value,
        "christoffersen_p": chr_.p_value,
        "worst_250": int(rolling_count.max()),
        "pct_days_red": 100 * (zones == "red").mean(),
        "zone_now": basel_zone(int(rolling_count.iloc[-1])),
    }


def verdict(p: float) -> str:
    return "reject" if p < 0.05 else "pass"


def plot(results: dict[str, pd.DataFrame]) -> None:
    fig, axes = plt.subplots(2, 1, figsize=(11, 7), sharex=True, sharey=True)
    for ax, (name, bt) in zip(axes, results.items()):
        breaches = bt[bt["breach"]]
        ax.plot(bt.index, bt["return"], lw=0.4, color="#888780", label="Daily return")
        ax.plot(bt.index, -bt["var"], lw=0.9, color="#185FA5", label="99% VaR (as a loss)")
        ax.scatter(breaches.index, breaches["return"], s=12, color="#C0392B",
                   zorder=3, label=f"Breach ({len(breaches)})")
        ax.set_title(f"{name}: {len(breaches)} breaches vs {len(bt) * P:.0f} expected")
        ax.set_ylabel("Return (%)")
        ax.legend(frameon=False, fontsize=8, loc="lower right")
    fig.tight_layout()
    FIG_FILE.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG_FILE)
    plt.close(fig)


def main() -> None:
    r = load_returns()
    results = {
        "Normal GARCH": rolling_var(GARCH(), r, P, WINDOW, REFIT_EVERY),
        "Student-t GARCH": rolling_var(StudentTGARCH(), r, P, WINDOW, REFIT_EVERY),
    }
    rows = [summarize(name, bt) for name, bt in results.items()]
    plot(results)

    first = next(iter(results.values())).index
    table = "\n".join(
        f"| {s['model']} | {s['breaches']} | {s['expected']:.1f} | {s['rate_pct']:.2f}% "
        f"| {s['kupiec_p']:.3f} ({verdict(s['kupiec_p'])}) "
        f"| {s['christoffersen_p']:.3f} ({verdict(s['christoffersen_p'])}) "
        f"| {s['worst_250']} | {s['pct_days_red']:.1f}% | {s['zone_now']} |"
        for s in rows
    )
    text = f"""# Week 4: out-of-sample 99% VaR backtest on SPY

Test period: {first[0].date()} to {first[-1].date()} ({len(first):,} trading days).
Each day's VaR uses only earlier data: re-fit every {REFIT_EVERY} days on the
previous {WINDOW:,} days. Generated by `notebooks/04_var_backtest.py`.

![VaR backtest](figures/05_var_backtest.png)

| Model | Breaches | Expected | Rate | Kupiec p | Christoffersen p | Worst 250-day count | Days in red zone | Zone now |
| --- | --- | --- | --- | --- | --- | --- | --- | --- |
{table}

- **Kupiec** tests whether the breach rate is 1%; **Christoffersen** tests
  whether breaches cluster. p < 0.05 rejects the model.
- **Basel zones** (99% VaR, 250 days): green 0-4, yellow 5-9, red 10+.
"""
    REPORT_FILE.write_text(text)

    for s in rows:
        print(f"{s['model']:<16} breaches {s['breaches']:>3} (expected {s['expected']:.1f}, "
              f"rate {s['rate_pct']:.2f}%)  Kupiec p {s['kupiec_p']:.3f}  "
              f"Christoffersen p {s['christoffersen_p']:.3f}  worst 250-day {s['worst_250']}  "
              f"zone now {s['zone_now']}")
    print(f"\nSaved {FIG_FILE.relative_to(PROJECT_ROOT)} and {REPORT_FILE.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()