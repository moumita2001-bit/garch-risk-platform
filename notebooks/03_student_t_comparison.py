"""Week 3: normal vs Student-t GARCH(1,1) on SPY, validated against `arch`.

1. Fits both models and compares log-likelihood, AIC and BIC.
2. Checks how fat-tailed the standardized residuals z_t = eps_t / sigma_t still are.
3. Compares my Student-t estimates with the `arch` package (dist="t").
Writes the results to docs/student_t_comparison.md.

Usage:
    python notebooks/03_student_t_comparison.py
"""

from pathlib import Path

import numpy as np
import pandas as pd
from arch import arch_model
from scipy import stats

from volrisk.models import GARCH, StudentTGARCH, StudentTParams

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_FILE = PROJECT_ROOT / "data" / "processed" / "spy.csv"
REPORT_FILE = PROJECT_ROOT / "docs" / "student_t_comparison.md"


def load_returns() -> np.ndarray:
    df = pd.read_csv(DATA_FILE, parse_dates=["date"]).set_index("date")
    return (100 * df["log_return"]).dropna().to_numpy()


def standardized_residuals(model, params, r: np.ndarray) -> np.ndarray:
    sigma2 = model.conditional_variance(params, r)
    return (r - params.mu) / np.sqrt(sigma2)


def fit_arch_t(r: np.ndarray) -> StudentTParams:
    res = arch_model(r, mean="Constant", vol="GARCH", p=1, q=1, dist="t").fit(disp="off")
    p = res.params
    return StudentTParams(
        mu=float(p["mu"]), omega=float(p["omega"]), alpha=float(p["alpha[1]"]),
        beta=float(p["beta[1]"]), nu=float(p["nu"]),
    )


def fmt(x: float) -> str:
    return f"{round(x, 4) + 0.0:+.4f}"


def main() -> None:
    r = load_returns()
    normal_model, t_model = GARCH(), StudentTGARCH()
    normal_fit, t_fit = normal_model.fit(r), t_model.fit(r)

    z_normal = standardized_residuals(normal_model, normal_fit.params, r)
    z_t = standardized_residuals(t_model, t_fit.params, r)
    nu = t_fit.params.nu

    # How many |z| > 4 days each distribution predicts, vs how many happened
    expected_normal = len(r) * 2 * stats.norm.sf(4)
    t_scale = np.sqrt((nu - 2) / nu)  # standardized t: P(|z|>4) = P(|T| > 4 / scale)
    expected_t = len(r) * 2 * stats.t.sf(4 / t_scale, df=nu)
    actual_4sd = int((np.abs(z_normal) > 4).sum())

    theirs = fit_arch_t(r)
    rows = [
        ("mu", t_fit.params.mu, theirs.mu),
        ("omega", t_fit.params.omega, theirs.omega),
        ("alpha", t_fit.params.alpha, theirs.alpha),
        ("beta", t_fit.params.beta, theirs.beta),
        ("nu", t_fit.params.nu, theirs.nu),
    ]
    arch_table = "\n".join(f"| {n} | {a:.4f} | {b:.4f} | {fmt(a - b)} |" for n, a, b in rows)

    winner = "Student-t" if t_fit.bic < normal_fit.bic else "Normal"
    text = f"""# Week 3: normal vs Student-t GARCH(1,1) on SPY

Data: {len(r):,} daily SPY log returns in percent.
Generated by `notebooks/03_student_t_comparison.py`.

## Model comparison

| | Normal | Student-t |
| --- | --- | --- |
| alpha | {normal_fit.params.alpha:.4f} | {t_fit.params.alpha:.4f} |
| beta | {normal_fit.params.beta:.4f} | {t_fit.params.beta:.4f} |
| alpha + beta | {normal_fit.params.persistence:.4f} | {t_fit.params.persistence:.4f} |
| nu | – | {nu:.2f} |
| Log-likelihood | {normal_fit.log_likelihood:.2f} | {t_fit.log_likelihood:.2f} |
| AIC (lower is better) | {normal_fit.aic:.2f} | {t_fit.aic:.2f} |
| BIC (lower is better) | {normal_fit.bic:.2f} | {t_fit.bic:.2f} |

BIC prefers the **{winner}** model (difference {abs(normal_fit.bic - t_fit.bic):.1f}).

## Are the residuals still fat-tailed?

If a model is right, z_t = eps_t / sigma_t should follow its assumed distribution.

| | Value |
| --- | --- |
| Excess kurtosis of raw returns | {stats.kurtosis(r):.2f} |
| Excess kurtosis of z_t (normal GARCH) | {stats.kurtosis(z_normal):.2f} |
| Excess kurtosis implied by fitted nu, 6/(nu-4) | {t_fit.params.excess_kurtosis_of_shocks:.2f} |
| Days with abs(z_t) > 4 (normal GARCH) | {actual_4sd} |
| Expected under normal shocks | {expected_normal:.1f} |
| Expected under t shocks with nu = {nu:.1f} | {expected_t:.1f} |

## Validation: my Student-t GARCH vs `arch` (dist="t")

| Parameter | Mine | arch | Difference |
| --- | --- | --- | --- |
{arch_table}

My log-likelihood at arch's parameters: {t_model.log_likelihood(theirs, r):.2f}
(my maximum: {t_fit.log_likelihood:.2f}). Converged: {t_fit.converged}.
"""
    REPORT_FILE.write_text(text)

    print(f"{'':<28}{'Normal':>12}{'Student-t':>12}")
    print(f"{'Log-likelihood':<28}{normal_fit.log_likelihood:>12.2f}{t_fit.log_likelihood:>12.2f}")
    print(f"{'AIC':<28}{normal_fit.aic:>12.2f}{t_fit.aic:>12.2f}")
    print(f"{'BIC':<28}{normal_fit.bic:>12.2f}{t_fit.bic:>12.2f}")
    print(f"\nnu = {nu:.2f}; residual kurtosis (normal GARCH) = {stats.kurtosis(z_normal):.2f}")
    print(f"|z| > 4 days: {actual_4sd} actual, {expected_normal:.1f} normal, {expected_t:.1f} t")
    print(f"\n{'':<10}{'mine':>10}{'arch':>10}")
    for n, a, b in rows:
        print(f"{n:<10}{a:>10.4f}{b:>10.4f}")
    print(f"\nSaved report to {REPORT_FILE.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()